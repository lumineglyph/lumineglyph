// Astro integration: subsets the Japanese heading font (Shippori Mincho) to the characters it renders.
//
// Japanese body text uses the visitor's system font (see global.css --sans and fonts/README.md).
// Shippori Mincho is the brand typeface for the Japanese headings only, and that text is fixed and
// known at build time. Before each dev/build run, this reads those headings from the Japanese copy,
// cuts each source font in fonts/ down to their characters (about 15 KB instead of 1.4 MB), and
// writes src/generated/fonts/japanese.css with matching @font-face rules. Base.astro imports it.
//
// Each weight gets only the text set in that weight. The browser doesn't borrow a missing glyph from
// another weight; it falls back to the next font in --serif-jp (Hiragino Mincho, Yu Mincho).
// So if you give another element `font-family: var(--serif-jp)` on Japanese pages, add its copy key
// below, or its characters will render in the fallback mincho font.

import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
import subsetFont from "subset-font";

// Bump when this file's output format changes, to invalidate the cache.
const VERSION = 2;

const COPY_FILE = "src/i18n/ja.json";

// `keys` are paths into the Japanese copy; `*` matches every item of an array.
// They follow the --serif-jp rules in global.css and works.css.
const FACES = [
  {
    family: "Shippori Mincho",
    weight: 400,
    file: "shippori-mincho-japanese-400-normal.woff2",
    keys: [
      "hero.title", // .hero h1
      "about.title", // .h2
      "services.title",
      "works.title",
      "team.title",
      "process.title",
      "team.moena.name", // .profile .pname
      "team.matthew.name",
      "worksPage.title", // .w-title
      "notFound.title",
    ],
  },
  {
    family: "Shippori Mincho",
    weight: 500,
    file: "shippori-mincho-japanese-500-normal.woff2",
    keys: ["services.items.*.title"], // .service h3
  },
];

// CJK radicals, kana, kanji, Japanese punctuation and full-width forms all start at U+2E80.
// Anything below that (Latin, spaces, “quotes”) comes from Fontsource's latin files.
const FIRST_CJK = 0x2e80;

export default function subsetFonts() {
  return {
    name: "subset-japanese-fonts",
    hooks: {
      "astro:config:setup": async ({ config, logger, addWatchFile }) => {
        const root = fileURLToPath(config.root);
        // Restart `astro dev` when the copy changes, so the subsets are rebuilt.
        addWatchFile(path.join(root, COPY_FILE));
        await generate(root, logger);
      },
    },
  };
}

async function generate(root, logger) {
  const outDir = path.join(root, "src", "generated", "fonts");
  const copy = JSON.parse(fs.readFileSync(path.join(root, COPY_FILE), "utf8"));

  const faces = FACES.map((face) => {
    const chars = new Set();
    for (const key of face.keys) {
      const values = pick(copy, key.split("."));
      if (values.length === 0) throw new Error(`subset-fonts: no text at "${key}" in ${COPY_FILE}`);
      for (const value of values) {
        for (const c of value) if (c.codePointAt(0) >= FIRST_CJK) chars.add(c);
      }
    }
    const codepoints = [...chars].map((c) => c.codePointAt(0)).sort((a, b) => a - b);
    return { ...face, codepoints, text: String.fromCodePoint(...codepoints) };
  });

  // Skip the work when nothing changed since the last run.
  const stampFile = path.join(outDir, ".stamp");
  const stamp = crypto.createHash("sha256").update(`${VERSION}\n${JSON.stringify(faces)}`).digest("hex");
  if (fs.existsSync(stampFile) && fs.readFileSync(stampFile, "utf8") === stamp) return;

  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });

  let css = "/* Generated by integrations/subset-fonts.mjs from fonts/. Do not edit. */\n";
  const sizes = [];
  for (const face of faces) {
    if (face.codepoints.length === 0) continue;
    const source = fs.readFileSync(path.join(root, "fonts", face.file));
    const subset = await subsetFont(source, face.text, { targetFormat: "woff2" });
    const name = face.file.replace("-japanese-", "-").replace("-normal", "");
    fs.writeFileSync(path.join(outDir, name), subset);
    sizes.push(`${face.weight}: ${face.codepoints.length} characters, ${(subset.length / 1024).toFixed(1)} KB`);
    css += `@font-face{font-family:"${face.family}";font-style:normal;font-weight:${face.weight};font-display:swap;src:url("./${name}") format("woff2");unicode-range:${toUnicodeRange(face.codepoints)}}\n`;
  }
  fs.writeFileSync(path.join(outDir, "japanese.css"), css);
  fs.writeFileSync(stampFile, stamp);
  logger.info(`Subset Shippori Mincho (${sizes.join("; ")})`);
}

// pick({a: [{b: "x"}, {b: "y"}]}, ["a", "*", "b"]) → ["x", "y"]
function pick(value, keys) {
  if (keys.length === 0) return typeof value === "string" ? [value] : [];
  const [key, ...rest] = keys;
  if (key === "*") return Array.isArray(value) ? value.flatMap((item) => pick(item, rest)) : [];
  return value && typeof value === "object" && key in value ? pick(value[key], rest) : [];
}

// [0x3041, 0x3042, 0x3043, 0x4e00] → "U+3041-3043,U+4E00"
function toUnicodeRange(codepoints) {
  const parts = [];
  for (let i = 0; i < codepoints.length; i++) {
    const start = codepoints[i];
    while (codepoints[i + 1] === codepoints[i] + 1) i++;
    const hex = (n) => n.toString(16).toUpperCase();
    parts.push(start === codepoints[i] ? `U+${hex(start)}` : `U+${hex(start)}-${hex(codepoints[i])}`);
  }
  return parts.join(",");
}
